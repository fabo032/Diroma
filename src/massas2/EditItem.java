    private void excluirBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirBTNActionPerformed
        // TODO add your handling code here:
        
        int id = Integer.parseInt(idTxt.getText());
        DaoProd daoprod = new DaoProd();
        daoprod.excluir(id);
        
        idTxt.setText("");
        tipTxt.setSelectedItem("");
        quanTxt.setValue("0");
        

        JOptionPane.showMessageDialog(null, "Exclusão realizada com sucesso!!");

        dispose();
    }//GEN-LAST:event_excluirBTNActionPerformed

    private void editBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editBTNActionPerformed
        int id = Integer.parseInt(idTxt.getText());
        String produto = txtProd1.getText();
        String tip = tipTxt.getSelectedItem().toString();
        int quant = Integer.parseInt(quanTxt.getValue().toString());

        Prod prod_edit = new Prod();
        prod_edit.setId(id);
        prod_edit.setProduto(produto);
        prod_edit.setTipo(tip);
        prod_edit.setQuantidade(quant);

        DaoProd daoprod = new DaoProd();
        daoprod.editar(prod_edit);

        idTxt.setText("");
        txtProd1.setText("");
        tipTxt.setSelectedItem("");
        quanTxt.setValue("0");

        JOptionPane.showMessageDialog(null, "Edição realizada com sucesso!!");

        dispose();
    }//GEN-LAST:event_editBTNActionPerformed

