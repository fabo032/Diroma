    private void pesBntActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pesBntActionPerformed
    int idPesquisa = Integer.parseInt(codTET.getText());
    DaoProd daoprod = new DaoProd();
    Prod prod = daoprod.getProd(idPesquisa);
    if (prod == null){
        JOptionPane.showMessageDialog(this,"item não encontrado");
}
    else{
        idTxt.setText(String.valueOf(prod.getId()));
        txtProd1.setText(prod.getProduto());
        tipTxt.setSelectedItem(prod.getTipo());
        quanTxt.setValue(prod.getQuantidade());
    }
            
    }//GEN-LAST:event_pesBntActionPerformed

